#!/bin/bash
# RDS 역할 MySQL 의 마스터 계정. 컨테이너가 처음 뜰 때 root 로 한 번 돈다.
# 권한은 RDS for MySQL 8.0.36 이상 마스터 계정 목록을 따른다(SUPER · SYSTEM_VARIABLES_ADMIN · CONNECTION_ADMIN 없음).
# 8.4 에서 없어진 SET_USER_ID 는 SET_ANY_DEFINER 로 바꿨다. 앱 계정은 20-rds-accounts.sh 가 만든다.
set -euo pipefail
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE USER 'nova_master'@'%' IDENTIFIED BY '$PW_NOVA_MASTER';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, RELOAD, PROCESS, REFERENCES, INDEX, ALTER, SHOW DATABASES,
      CREATE TEMPORARY TABLES, LOCK TABLES, EXECUTE, REPLICATION SLAVE, REPLICATION CLIENT, CREATE VIEW, SHOW VIEW,
      CREATE ROUTINE, ALTER ROUTINE, CREATE USER, EVENT, TRIGGER, CREATE ROLE, DROP ROLE
   ON *.* TO 'nova_master'@'%' WITH GRANT OPTION;
GRANT APPLICATION_PASSWORD_ADMIN, ROLE_ADMIN, SET_ANY_DEFINER, XA_RECOVER_ADMIN ON *.* TO 'nova_master'@'%' WITH GRANT OPTION;
SQL
